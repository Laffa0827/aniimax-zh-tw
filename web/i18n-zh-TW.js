// Translate the long facility tooltips without changing the underlying data.
export function zhTooltip(text) {
    if (!text) return text;
    let out = text;
    const entries = Object.entries(ZH_TW.items)
        .filter(([id, zh]) => zh && id && id.length > 2)
        .sort((a, b) => b[0].length - a[0].length);
    // Data tooltips use the human-readable English item names, so match against the
    // same labels used by the recipe tables. This is deliberately display-only.
    const englishNames = {
        'Wheat':'小麥',
        'Quick Potato':'高速馬鈴薯',
        'Premium Wheat':'高級小麥',
        'Willow Wood':'柳木',
        'Palm Bark':'棕皮',
        'Quick Maple Syrup':'高速楓糖漿',
        'Copper Ore':'銅礦石',
        'Deep Rock Spring Water':'深岩泉水',
        'Sea Salt':'海鹽',
        'Wood Blocks':'木塊','Mineral Sand':'礦砂'
    };
    for (const [en, zh] of Object.entries(englishNames)) out = out.replaceAll(en, zh);
    out = out.replaceAll('Also yields', '另外產出').replaceAll('needs Warm', '需要溫暖').replaceAll('need Warm', '需要溫暖')
        .replaceAll('needs Cool', '需要寒冷').replaceAll('need Cool', '需要寒冷')
        .replaceAll('need Adequate', '需要適宜').replaceAll('Not yet verified in game.', '尚未在遊戲中確認。')
        .replaceAll('Provides Warm or Scorching growing conditions for crops that need one', '提供需要溫暖或炎熱環境的作物生長條件')
        .replaceAll('Provides Cool or Freeze growing conditions for crops that need one', '提供需要寒冷或冰凍環境的作物生長條件')
        .replaceAll('Provides Adequate growing conditions for crops that need one', '提供需要適宜環境的作物生長條件')
        .replaceAll('The calculator picks whichever mode is more profitable.', '計算器會選擇收益較高的環境模式。')
        .replaceAll('Covers a 9x9 area around itself; how many plots fit depends on what shares it.', '覆蓋自身周圍 9×9 的範圍；可容納多少土地取決於共享範圍的設施。')
        .replaceAll('Makes Aniimo EXP, not Home Coins.', '產出 Aniimo 經驗，而不是家園幣。')
        .replaceAll('Unlock levels not yet confirmed in game.', '解鎖等級尚未在遊戲中確認。')
        .replaceAll('Aniipods are for catching Aniimo, not for selling.', 'Aniipod 用於捕捉 Aniimo，不能販售。')
        .replaceAll('Turns Wood Blocks into RV level-up materials.', '將木塊加工成 RV 升級材料。')
        .replaceAll('Turns Mineral Sand into RV level-up materials.', '將礦砂加工成 RV 升級材料。');
    return out;
}

export function zhItem(name) {
    if (!name) return name;
    return ZH_TW.items[name] || ZH_TW.ui[name] || name.split('_').map(w => w ? w[0].toUpperCase() + w.slice(1) : w).join(' ');
}
